    eq_lats = df_eq["latitude"].to_numpy()
    eq_lons = df_eq["longitude"].to_numpy()
    eq_mags = df_eq["mag"].to_numpy()

    pop_lats = df_pop["lat"].to_numpy()
    pop_lons = df_pop["lon"].to_numpy()
    pop_totals = df_pop["hh_total"].to_numpy()

    affected_pops = []

    for eq_lat, eq_lon, eq_mag in zip(eq_lats, eq_lons, eq_mags):
        # Compute distances for all townships at once
        distances_km = np.array([geodesic((eq_lat, eq_lon), (pl, plon)).km for pl, plon in zip(pop_lats, pop_lons)])

        # Define weights based on distances
        weights = np.where(distances_km <= 50, 1,
                   np.where(distances_km <= 100, 0.5,
                   np.where(distances_km <= 200, 0.2, 0)))

        # Compute affected population
        affected_pop = np.sum(pop_totals * weights * (eq_mag / 7.0))
        affected_pops.append(int(affected_pop))

    df_eq["Estimated_Affected_Pop"] = affected_pops
    return df_eq

