# 🔹 **Population Estimation Function (No Region Filter)**
def estimate_affected_population(eq_lat, eq_lon, eq_mag):
    affected_pop = 0
    selected_pop_data = df_pop_mm.copy()  # Use entire dataset

    # Ensure numeric types
    selected_pop_data["Latitude"] = pd.to_numeric(selected_pop_data["Latitude"], errors="coerce")
    selected_pop_data["Longitude"] = pd.to_numeric(selected_pop_data["Longitude"], errors="coerce")
    selected_pop_data["Both sexes"] = pd.to_numeric(selected_pop_data["Both sexes"], errors="coerce")

    print(f"\n🔍 Earthquake at ({eq_lat}, {eq_lon}) M{eq_mag}")
    print(f"📌 Analyzing {len(selected_pop_data)} population points...")

    for _, row in selected_pop_data.iterrows():
        region_lat = row["Latitude"]
        region_lon = row["Longitude"]
        total_pop = row["Both sexes"]

        # Skip invalid data
        if pd.isna(region_lat) or pd.isna(region_lon) or pd.isna(total_pop):
            continue

        # Calculate distance from earthquake to region center
        distance_km = geodesic((eq_lat, eq_lon), (region_lat, region_lon)).km

        # Define dynamic buffer based on earthquake magnitude
        max_radius = eq_mag * 15  # Example: M6.5 -> 65 km radius

        if distance_km <= max_radius:
            # Use an exponential decay function to reduce impact with distance
            weight = np.exp(-distance_km / (max_radius / 2))
            magnitude_factor = (eq_mag / 7.0) ** 2  # Scale by magnitude

            affected_pop += total_pop * weight * magnitude_factor

            print(f"🌍 Region at ({region_lat}, {region_lon}) | Pop: {total_pop}")
            print(f"   ➡️ Distance: {distance_km:.2f} km, Weight: {weight:.4f}, Mag Factor: {magnitude_factor:.4f}")

    print(f"🎯 Estimated Affected Population: {int(affected_pop)}\n")
    return int(affected_pop)


# 🔹 **Map Visualization Function**
def plot_earthquake_map(start_date=None, end_date=None):
    # Default dates: 2025-01-01 to today
    if start_date is None:
        start_date = datetime(2025, 1, 1)
    if end_date is None:
        end_date = datetime.today()

    start_date = pd.to_datetime(start_date)
    end_date = pd.to_datetime(end_date)

    # Filter earthquakes by selected date range
    filtered_eq = df_eq_filtered[(df_eq_filtered["time"] >= start_date) & (df_eq_filtered["time"] <= end_date)].copy()

    if filtered_eq.empty:
        print("⚠️ No earthquakes found in the selected time range.")
        return None

    # Compute affected population for each earthquake (without region filtering)
    filtered_eq["Weighted_Affected_Pop"] = filtered_eq.apply(
        lambda row: estimate_affected_population(row["latitude"], row["longitude"], row["mag"]),
        axis=1
    )

    # Ensure affected population is not all zeros
    print("📊 Min Affected Pop:", filtered_eq["Weighted_Affected_Pop"].min())
    print("📊 Max Affected Pop:", filtered_eq["Weighted_Affected_Pop"].max())

    # Create Folium Map
    myanmar_map = folium.Map(location=[21.0, 96.0], zoom_start=6)

    # 🔹 **Add Population Heatmap**
    heat_data = [
        [row["Latitude"], row["Longitude"], row["Both sexes"]]
        for _, row in df_pop_mm.iterrows()
    ]

    if heat_data:
        HeatMap(heat_data, min_opacity=0.4, radius=20, blur=10, max_zoom=1).add_to(myanmar_map)

    # 🔹 **Add Earthquake Markers**
    for _, row in filtered_eq.iterrows():
        weighted_population = row["Weighted_Affected_Pop"]

        folium.CircleMarker(
            location=[row["latitude"], row["longitude"]],
            radius=max(5, np.log1p(weighted_population) / 2),
            color="red",
            fill=True,
            fill_color="red",
            fill_opacity=min(0.9, weighted_population / 1e6) if weighted_population > 0 else 0.3,
            popup=(
                f"<b>Date:</b> {row['time'].date()}<br>"
                f"<b>Magnitude:</b> {row['mag']}<br>"
                f"<b>Estimated Affected Population:</b> {int(weighted_population):,}"
            ),
        ).add_to(myanmar_map)

    display(myanmar_map)


