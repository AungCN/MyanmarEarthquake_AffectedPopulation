def plot_earthquake_map(start_date=None, end_date=None, export_csv=False):
    # Default dates: 2025-01-01 to today
    if start_date is None:
        start_date = datetime(2025, 1, 1)
    if end_date is None:
        end_date = datetime.today()

    start_date = pd.to_datetime(start_date)
    end_date = pd.to_datetime(end_date)

    # Filter earthquakes by selected date range
    filtered_eq = df_eq_filtered[(df_eq_filtered["time"] >= start_date) & (df_eq_filtered["time"] <= end_date)].copy()

    if filtered_eq.empty:
        print("⚠️ No earthquakes found in the selected time range.")
        return None

    # Compute affected population for each earthquake (without region filtering)
    filtered_eq["Weighted_Affected_Pop"] = filtered_eq.apply(
        lambda row: estimate_affected_population(row["latitude"], row["longitude"], row["mag"]),
        axis=1
    )

    # Export CSV if enabled
    if export_csv:
        filename = f"earthquake_data_{start_date.date()}_to_{end_date.date()}.csv"
        filtered_eq.to_csv(filename, index=False)
        print(f"📂 Exported filtered data to: {filename}")

    # Ensure affected population is not all zeros
    print("📊 Min Affected Pop:", filtered_eq["Weighted_Affected_Pop"].min())
    print("📊 Max Affected Pop:", filtered_eq["Weighted_Affected_Pop"].max())

    # Create Folium Map
    myanmar_map = folium.Map(location=[21.0, 96.0], zoom_start=5)

    # 🔹 **Add Population Heatmap**
    heat_data = [
        [row["lat"], row["lon"], row["hh_total"]]
        for _, row in df_pop_mm.iterrows()
    ]

    if heat_data:
        HeatMap(heat_data, min_opacity=0.1, radius=5, blur=2, max_zoom=1).add_to(myanmar_map)

    # 🔹 **Add Earthquake Markers**
    for _, row in filtered_eq.iterrows():
        weighted_population = row["Weighted_Affected_Pop"]

        folium.CircleMarker(
            location=[row["latitude"], row["longitude"]],
            radius=max(5, np.log1p(weighted_population) / 2),
            color="red",
            fill=True,
            fill_color="red",
            fill_opacity=min(0.9, weighted_population / 1e6) if weighted_population > 0 else 0.3,
            popup=(
                f"<b>Date:</b> {row['time'].date()}<br>"
                f"<b>Magnitude:</b> {row['mag']}<br>"
                f"<b>Estimated Affected Population:</b> {int(weighted_population):,}"
            ),
        ).add_to(myanmar_map)

    display(myanmar_map)


